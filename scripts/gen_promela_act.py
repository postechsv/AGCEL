#!/usr/bin/env python3
"""Generate the parts of the PROMELA semantics that are derived from its rules, and the
action-recording variants of benchmark files.

canStep, in semantics/promela-semantics.maude between the BEGIN canStep / END canStep lines:
canStep(GS) is true when some rule other than [loose] can rewrite GS. K gives [loose] the
attribute owise, a Maude rule cannot carry it, so [loose] has the condition not canStep(...).
The block holds one equation per rule other than [loose], with the left-hand side and the
condition of that rule, and canStep(GS) = false [owise].

semantics/promela-semantics-act.maude (module PROMELA-SEMANTICS-ACT) is PROMELA-SEMANTICS with
the last executed action recorded in the configuration: every rule matches last(LA) and writes
last(exec(<label>, tag(<pid>), prefix(<k>, propKsize))), where <pid> and <k> are the pid and
the computation, before the step, of the process that acted. That process is the first
proc(pid(P) ... k(KT) ...) of the left-hand side; a rule that matches no process (NO_PROCESS)
records the pid it affects and an empty computation. LA ranges over the kind [Action]: a rule
applies whatever was recorded before. initT gets last(noAct). The vocabulary (sorts, last,
exec, prefix, propKsize, tag) is hand-written in semantics/promela-action.maude.

A benchmark file (safety search or RL analysis layer) is turned into its variant over
PROMELA-SEMANTICS-ACT by replacing the imports and adding last(noAct) to its init terms
(the constants whose name starts with init).

  gen_promela_act.py semantics            rewrite the canStep block and semantics/promela-semantics-act.maude
  gen_promela_act.py semantics --check    exit 1 if either is not what would be generated
  gen_promela_act.py rules                the acting process each rule records
  gen_promela_act.py file <in.maude> <out.maude> [--focus IDS] [--ksize N]
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEM = os.path.join(REPO, 'semantics')
SRC = os.path.join(SEM, 'promela-semantics.maude')
DST = os.path.join(SEM, 'promela-semantics-act.maude')
NO_PROCESS = {'loose': 'PID'}  # rule: the variable holding the pid it affects (the lock holder)

HEADER = '''*** GENERATED by scripts/gen_promela_act.py from promela-semantics.maude -- do not edit by hand.
*** PROMELA-SEMANTICS with the last executed action recorded in the configuration:
*** every rule matches last(LA) and writes
***   last(exec(<label>, tag(<pid>), prefix(<k>, propKsize)))
*** for the pid and the computation, before the step, of the process that acted (the first
*** proc of the left-hand side; [loose] matches no process and records the lock holder with
*** an empty computation). initT starts with last(noAct). The K rule each rule ports is
*** quoted in promela-semantics.maude; the vocabulary is in promela-action.maude.
*** canStep, the condition of [loose], is copied as generated there. [loose] passes it the
*** configuration without the last(...) item, so a recorded computation that has no sort
*** (#run(X, EL) before [run-eval]) does not keep its equations from matching.

load promela-action.maude .
'''
RULE = re.compile(r'^[ \t]*c?rl \[([^\]]+)\] :[ \t]*\n', re.M)
OWISE = ('loose',)  # the rules K marks [owise]: their condition is not canStep(<left-hand side>)
CS_BEGIN = '  --- BEGIN canStep -- generated by scripts/gen_promela_act.py from the rules above; do not edit by hand\n'
CS_END = '  --- END canStep\n'


def balanced(s, i, op, cl):
    """index just past the bracket closing the one opening at s[i]"""
    assert s[i] == op, s[i:i + 20]
    d = 0
    for j in range(i, len(s)):
        if s[j] == op: d += 1
        elif s[j] == cl:
            d -= 1
            if d == 0: return j + 1
    raise ValueError('unbalanced: ' + s[i:i + 60])


def acting(label, lhs):
    """(pid variable, computation before the step) recorded by the rule with this left-hand side"""
    m = re.search(r'\bproc\(pid\((\w+)\)', lhs)
    if m is None:
        pid = NO_PROCESS[label]
        assert re.search(rf'\b{pid}\b', lhs), label
        return pid, '.K'
    assert label not in NO_PROCESS, label
    end = balanced(lhs, m.start() + len('proc'), '(', ')')
    k = re.search(r'\bk\(', lhs[m.end():end])
    i = m.end() + k.end() - 1
    return m.group(1), lhs[i + 1:balanced(lhs, i, '(', ')') - 1]


def rule_blocks(text):
    """[(label, start, end)] of the rule statements"""
    out = []
    for m in RULE.finditer(text):
        e = re.compile(r' \.[ \t]*\n').search(text, m.end())
        out.append((m.group(1), m.start(), e.end(), m.end()))
    return out


def rule_parts(label, block, body):
    """(head, left-hand side, arrow line, right-hand side, the rest: ' .' or the condition) of
    the rule statement `block`, whose left-hand side starts at offset `body`"""
    head, rest = block[:body], block[body:]
    arrows = list(re.finditer(r'\n[ \t]*=>[ \t]*\n', rest))
    assert len(arrows) == 1, label
    lhs, rhs = rest[:arrows[0].start()], rest[arrows[0].end():]
    i, j = lhs.index('['), rhs.index('[')
    assert not lhs[:i].strip() and not rhs[:j].strip(), label
    assert balanced(lhs, i, '[', ']') == len(lhs.rstrip()), label
    e = balanced(rhs, j, '[', ']')
    return head, lhs, arrows[0].group(0), rhs[:e], rhs[e:]


def condition(label, head, tail):
    """the condition of a rule statement ('' for an unconditional rule)"""
    t = tail.strip()
    assert t.endswith('.'), label
    c = t[:-1].strip()
    assert (c == '' and head.lstrip().startswith('rl ')) or (c.startswith('if ') and head.lstrip().startswith('crl ')), label
    return c[3:].strip() if c else ''


def record(label, block, body):
    """the rule statement `block` (its left-hand side starts at offset `body`) with the action recorded"""
    head, lhs, arrow, rhs, tail = rule_parts(label, block, body)
    i, j = lhs.index('['), rhs.index('[')
    pid, k = acting(label, lhs)
    pad = ' ' * (len(rhs[:j]) + 1)
    act = f'exec({label}, tag({pid}), ' + ('.K' if k == '.K' else f'prefix({k}, propKsize)') + ')'
    return (head + lhs[:i + 1] + 'last(LA:[Action]) ' + lhs[i + 1:] + arrow
            + rhs[:j + 1] + f'last({act})\n{pad}' + rhs[j + 1:] + tail), pid, k


def canstep(text):
    """(the canStep block of the rules in `text`, the labels it has an equation for)"""
    L = [CS_BEGIN.rstrip('\n'),
         '  --- canStep(GS): some rule other than [loose] can rewrite GS. One equation per rule, with',
         '  --- the left-hand side and the condition of that rule; false when none of them applies.',
         '  op canStep : GlobalState -> Bool .']
    rules, done, owise = rule_blocks(text), [], []
    for label, s, e, body in rules:
        head, lhs, _, _, tail = rule_parts(label, text[s:e], body - s)
        cond = condition(label, head, tail)
        if label in OWISE:   # its condition must be exactly: no other rule applies to what it matches
            assert ' '.join(cond.split()) == 'not canStep(' + ' '.join(lhs.split()) + ')', (label, cond)
            owise.append(label)
            continue
        L.append(f'  --- [{label}]')
        L.append(('  ceq' if cond else '  eq') + ' canStep(')
        L.append(lhs.rstrip() + ') = true' + (f'\n    if {cond} .' if cond else ' .'))
        done.append(label)
    assert sorted(owise) == sorted(OWISE), owise
    assert len(done) == len(rules) - len(OWISE) and len(set(done)) == len(done), 'one equation per rule other than [loose]'
    L.append('  eq canStep(GS:GlobalState) = false [owise] .')
    return '\n'.join(L) + '\n' + CS_END, done


def with_canstep(text):
    """`text` (promela-semantics.maude) with its canStep block regenerated from its rules"""
    assert text.count(CS_BEGIN) == 1 and text.count(CS_END) == 1
    a = text.index(CS_BEGIN)
    b = text.index(CS_END, a) + len(CS_END)
    return text[:a] + canstep(text[:a] + text[b:])[0] + text[b:]


def strip_comments(text):
    lines = [l for l in text.split('\n') if not l.lstrip().startswith(('---', '***'))]
    return re.sub(r'\n{3,}', '\n\n', '\n'.join(lines))


def semantics(text):
    """(module text, [(label, pid variable, computation)])"""
    out, pos, info = [], 0, []
    for label, s, e, body in rule_blocks(text):
        new, pid, k = record(label, text[s:e], body - s)
        out += [text[pos:s], new]; pos = e
        info.append((label, pid, k))
    text = ''.join(out) + text[pos:]
    labels = [l for l, _, _ in info]
    assert len(set(labels)) == len(labels)
    decl, line = [], '  ops'
    for l in labels:
        if len(line) + len(l) + 1 > 92:
            decl.append(line); line = '     '
        line += ' ' + l
    decl.append(line + ' : -> RuleLabel [ctor] .')
    head = 'mod PROMELA-SEMANTICS is\n  protecting PROMELA-HCHAN .\n'
    assert text.count(head) == 1
    text = text.replace(head, 'mod PROMELA-SEMANTICS-ACT is\n  protecting PROMELA-HCHAN .\n'
                        '  protecting PROMELA-ACTION .\n\n' + '\n'.join(decl) + '\n')
    init = 'eq initT(K) = [ proctypes(none)'
    assert text.count(init) == 1
    text = text.replace(init, 'eq initT(K) = [ last(noAct) proctypes(none)')
    load = 'load promela-functions.maude .\n'
    assert text.count(load) == 1
    text = strip_comments(text.replace(load, '')).strip('\n')
    return HEADER + '\n' + text + '\n', info


LOAD = re.compile(r'^load[ \t]+(\S+?)(?:\.maude)?[ \t]*\.?[ \t]*$', re.M)
MODULE = re.compile(r'^f?mod [^\n]* is\n.*?^endf?m[ \t]*\n', re.M | re.S)


def act_file(text, src_dir, focus=None, ksize=None):
    """the variant of a benchmark file over PROMELA-SEMANTICS-ACT. focus (a list of pids) and
    ksize, when given, are written as equations into the module that imports the semantics;
    an analysis file gets them from the module that runs it."""
    def load(m):
        p = os.path.normpath(os.path.join(src_dir, m.group(1) + '.maude'))
        b = os.path.basename(p)
        if b in ('promela-obs-generated.maude',) or b.startswith('focus-'):
            return ''   # the hook and the thin focus modules import the rules without the action
        if b == 'promela-semantics.maude':
            p = DST
        return f'load {p} .'
    text = LOAD.sub(load, text)
    # modules that set the focus or switch the hook on are the default run modules of an analysis file
    text = MODULE.sub(lambda m: '' if re.search(r'\b(PROMELA-OBS-GEN|FOCUS-\w+)\b', m.group(0)) else m.group(0), text)
    n = 0
    for name in ('PROMELA-SEMANTICS', 'PROMELA-AGCEL'):
        text, k = re.subn(rf'\b(protecting|pr|including|inc)[ \t]+{name}[ \t]+\.', rf'\1 {name}-ACT .', text)
        n += k
    assert n >= 1, 'no import of PROMELA-SEMANTICS or PROMELA-AGCEL'
    text, k = re.subn(r'\beq (init\w*) = \[', r'eq \1 = [ last(noAct)', text)
    assert k >= 1, 'no init term'
    if focus is not None or ksize is not None:
        eqs = ''
        if focus is not None:
            eqs += f"  eq focusIds = {', '.join(map(str, focus)) or 'mt'} .\n"
        if ksize is not None:
            eqs += f'  eq propKsize = {ksize} .\n'
        text, k = re.subn(r'^([ \t]*(?:protecting|pr) PROMELA-SEMANTICS-ACT \.[ \t]*\n)', r'\1' + eqs, text, count=1, flags=re.M)
        if k == 0:   # the import shares its line with other declarations
            text, k = re.subn(r'\b((?:protecting|pr) PROMELA-SEMANTICS-ACT \.)', r'\1\n' + eqs, text, count=1)
        assert k == 1, 'no module importing the semantics'
    return re.sub(r'\n{3,}', '\n\n', text)


def props_module(note, lists):
    """module ARM-PROPS over MODEL: for each (list name, short name, [(proposition, the same
    in mixfix form)]) a PropList constant; with a short name, a proposition is entered as
    <short name>(i) and defined by S |= <short name>(i) = S |= <proposition>, which keeps
    observation terms small"""
    L = ['*** GENERATED by scripts/run_extended_exp.py (gen_promela_act.props_module) -- do not edit by hand.']
    L += [f'*** {n}' for n in note]
    L += ['', 'mod ARM-PROPS is', '  pr MODEL .', '  var S : State .']
    for name, short, props in lists:
        L.append('')
        names = [p for p, _ in props]
        if short:
            L.append(f'  op {short} : Nat -> Prop [ctor] .')
            for i, (p, readable) in enumerate(props, 1):
                L.append(f'  --- {short}({i}): ' + ' '.join(readable.split()))
                L.append(f'  eq S |= {short}({i}) = S |= {p} .')
            names = [f'{short}({i})' for i in range(1, len(props) + 1)]
        L.append(f'  op {name} : -> PropList .')
        L.append(f'  eq {name} = ' + (' ; '.join(names) or 'nil') + ' .')
    return '\n'.join(L + ['endm', ''])


def main():
    a = sys.argv[1:]
    if a[:1] == ['semantics']:
        old = open(SRC).read()
        src = with_canstep(old)
        new, _ = semantics(src)
        if a[1:] == ['--check']:
            bad = ([f'the canStep block of {SRC}'] if src != old else []) \
                + ([DST] if not (os.path.exists(DST) and open(DST).read() == new) else [])
            print('in sync' if not bad else ' and '.join(bad) + ' differ from the generator output')
            sys.exit(1 if bad else 0)
        if src != old:
            with open(SRC, 'w') as f:
                f.write(src)
            print(f'rewrote the canStep block of {SRC}')
        with open(DST, 'w') as f:
            f.write(new)
        print(f'wrote {DST}')
    elif a[:1] == ['rules']:
        _, info = semantics(with_canstep(open(SRC).read()))
        for label, pid, k in info:
            print(f'{label:24s} {pid:5s} {k}')
    elif a[:1] == ['file'] and len(a) >= 3:
        focus = ksize = None
        if '--focus' in a:
            v = a[a.index('--focus') + 1]
            focus = [] if v == 'mt' else [int(c) for c in v]
        if '--ksize' in a:
            ksize = int(a[a.index('--ksize') + 1])
        src = os.path.abspath(a[1])
        with open(a[2], 'w') as f:
            f.write(act_file(open(src).read(), os.path.dirname(src), focus, ksize))
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
